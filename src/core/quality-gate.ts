export type CheckStatus = 'pass' | 'fail' | 'unverifiable' | 'na';

export const CHECK_STATUS_AR: Record<CheckStatus, string> = {
  pass: 'ناجح',
  fail: 'فاشل',
  unverifiable: 'متعذر التحقق',
  na: 'غير منطبق',
};

export interface QualityCheckpoint {
  readonly id: string;
  readonly domainId: number;
  readonly domainTitle: string;
  readonly title: string;
  readonly requirement: string;
  readonly fixableHint: string;
}

export interface QualityDomain {
  readonly id: number;
  readonly title: string;
  readonly checkpoints: readonly QualityCheckpoint[];
}

export interface CheckEvaluation {
  readonly id: string;
  readonly status: CheckStatus;
  readonly evidence?: string;
}

export interface QualityGateReport {
  readonly totalChecks: number; // دائماً 60
  readonly summary: {
    readonly pass: number;
    readonly fail: number;
    readonly unverifiable: number;
    readonly na: number;
    readonly applicableCount: number;
    readonly verifiedPassRatePct: number | null;
    readonly readyForDelivery: boolean;
    readonly verdictAr: string;
  };
  readonly domains: Array<{
    readonly id: number;
    readonly title: string;
    readonly pass: number;
    readonly fail: number;
    readonly unverifiable: number;
    readonly na: number;
    readonly items: Array<QualityCheckpoint & { status: CheckStatus; statusAr: string; evidence: string }>;
  }>;
  readonly masteryCriteria: Array<{
    readonly id: number;
    readonly title: string;
    readonly status: CheckStatus;
    readonly statusAr: string;
  }>;
  readonly blockers: Array<{ id: string; domainTitle: string; title: string; fixableHint: string }>;
}

