export function evaluateQualityGate(evaluations: CheckEvaluation[] = []): QualityGateReport {
  const byId = new Map<string, CheckEvaluation>();
  for (const ev of evaluations) {
    byId.set(ev.id, ev);
  }

  let pass = 0;
  let fail = 0;
  let unverifiable = 0;
  let na = 0;
  const blockers: QualityGateReport['blockers'] = [];

  const domains = QUALITY_DOMAINS.map((domain) => {
    let dPass = 0;
    let dFail = 0;
    let dUnv = 0;
    let dNa = 0;

    const items = domain.checkpoints.map((cp) => {
      const ev = byId.get(cp.id);
      let status: CheckStatus = ev?.status ?? 'unverifiable';
      let evidence = (ev?.evidence || '').trim();

      // قاعدة القسم 19: لا تمنح تقييماً ناجحاً دون دليل
      if (status === 'pass' && !evidence) {
        status = 'unverifiable';
        evidence = 'لم يُرفق دليل تحقق — حُوّل تلقائياً إلى متعذر التحقق التزاماً بالقسم 19.';
      }

      if (status === 'pass') {
        pass++;
        dPass++;
      } else if (status === 'fail') {
        fail++;
        dFail++;
        blockers.push({
          id: cp.id,
          domainTitle: domain.title,
          title: cp.title,
          fixableHint: cp.fixableHint,
        });
      } else if (status === 'na') {
        na++;
        dNa++;
      } else {
        unverifiable++;
        dUnv++;
      }

      return {
        ...cp,
        status,
        statusAr: CHECK_STATUS_AR[status],
        evidence: evidence || (status === 'na' ? 'غير منطبق على نطاق المهمة.' : 'بانتظار دليل التحقق.'),
      };
    });

    return {
      id: domain.id,
      title: domain.title,
      pass: dPass,
      fail: dFail,
      unverifiable: dUnv,
      na: dNa,
      items,
    };
  });

  const applicableCount = ALL_60_CHECKPOINTS.length - na;
  const verifiedPassRatePct =
    applicableCount > 0 ? Math.round((pass / applicableCount) * 1000) / 10 : null;

  const domainMap = new Map(domains.map((d) => [d.id, d]));
  const masteryCriteria = MASTERY_CRITERIA_10.map((criterion) => {
    const linked = criterion.domainIds.map((id) => domainMap.get(id)!);
    let status: CheckStatus = 'pass';
    if (linked.some((d) => d.fail > 0)) {
      status = 'fail';
    } else if (linked.every((d) => d.na === d.items.length)) {
      status = 'na';
    } else if (linked.some((d) => d.unverifiable > 0)) {
      status = 'unverifiable';
    }
    return {
      id: criterion.id,
      title: criterion.title,
      status,
      statusAr: CHECK_STATUS_AR[status],
    };
  });

  const readyForDelivery = fail === 0 && pass > 0 && unverifiable === 0;
  let verdictAr = '';
  if (fail > 0) {
    verdictAr = `مرفوض للتسليم النهائي: يوجد ${fail} بند فاشل يجب إصلاحه قبل التسليم.`;
  } else if (unverifiable > 0) {
    verdictAr = `معلّق جزئياً: لا توجد إخفاقات، لكن يوجد ${unverifiable} بند متعذر التحقق يحتاج أدلة فعلية.`;
  } else if (pass === 0) {
    verdictAr = 'لم يُفحص أي بند منطبق بدليل بعد.';
  } else {
    verdictAr = `معتمد للتسليم التنفيذي: جميع البنود المنطبقة (${pass}/${applicableCount}) ناجحة وموثقة بالأدلة.`;
  }

  return {
    totalChecks: ALL_60_CHECKPOINTS.length,
    summary: {
      pass,
      fail,
      unverifiable,
      na,
      applicableCount,
      verifiedPassRatePct,
      readyForDelivery,
      verdictAr,
    },
    domains,
    masteryCriteria,
    blockers,
  };
}
